import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { catalogCompleteness, catalogGroups, catalogProducts, catalogSubgroups } from "../src/data/catalog.ts";

const outputDir = path.join(process.cwd(), "supabase", "seed");
const sqlPath = path.join(outputDir, "catalog_seed.sql");
const manifestPath = path.join(outputDir, "catalog_seed_manifest.json");

function sqlString(value) {
  if (value === undefined || value === null) {
    return "null";
  }
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlBoolean(value) {
  return value ? "true" : "false";
}

function sqlArray(values) {
  if (!values?.length) {
    return "'{}'";
  }
  return `array[${values.map(sqlString).join(", ")}]`;
}

function assertCatalogCompleteness() {
  const failures = catalogCompleteness.productsPerLeaf.filter((item) => item.count < 15);
  if (failures.length) {
    throw new Error(`Catalog leaf collections below 15 products: ${JSON.stringify(failures)}`);
  }

  if (catalogCompleteness.actualProductCount !== 240) {
    throw new Error(`Expected 240 catalog products, got ${catalogCompleteness.actualProductCount}`);
  }

  const missingAssetPrompts = catalogProducts.filter((product) => !product.image.prompt || !product.image.alt);
  if (missingAssetPrompts.length) {
    throw new Error(`Products without image prompt/alt: ${missingAssetPrompts.map((item) => item.id).join(", ")}`);
  }
}

function groupRows() {
  return catalogGroups.map((group, index) => `(
    ${sqlString(group.id)},
    ${sqlString(group.name)},
    ${sqlString(group.description)},
    ${sqlString(group.customerPromise)},
    ${sqlString(group.measureNote)},
    ${sqlString(group.visualizationMode)},
    ${group.minimumProductsRequired},
    ${sqlArray(group.sourceUrls)},
    ${index + 1},
    true
  )`);
}

function subgroupRows() {
  return catalogSubgroups.map((subgroup, index) => `(
    ${sqlString(subgroup.id)},
    ${sqlString(subgroup.groupId)},
    ${sqlString(subgroup.name)},
    ${sqlString(subgroup.description)},
    ${sqlString(subgroup.customerPromise)},
    ${subgroup.minimumProductsRequired},
    ${index + 1},
    true
  )`);
}

function productRows() {
  return catalogProducts.map((product) => `(
    ${sqlString(product.id)},
    ${sqlString(product.groupId)},
    ${sqlString(product.subgroupId)},
    ${sqlString(product.name)},
    ${sqlString(product.shortDescription)},
    ${sqlString(product.materialFamily)},
    ${sqlString(product.colorName)},
    ${sqlString(product.colorHex)},
    ${sqlString(product.transparency)},
    ${sqlString(product.controlType)},
    ${sqlArray(product.compatibleMountingMethods)},
    ${sqlBoolean(product.sampleAvailable)},
    ${product.basePriceCents},
    ${product.pricePerSquareMeterCents},
    ${product.minWidthMm},
    ${product.maxWidthMm},
    ${product.minHeightMm},
    ${product.maxHeightMm},
    ${sqlArray(product.commerceBullets)},
    ${sqlArray(product.measurementWarnings)},
    true
  )`);
}

function assetRows() {
  return catalogProducts.map((product) => `(
    ${sqlString(product.id)},
    ${sqlString(product.image.status)},
    'product-photo',
    ${sqlString(product.image.url)},
    ${sqlString(product.image.alt)},
    ${sqlString(product.image.prompt)},
    ${sqlString(product.image.referenceSourceUrl)},
    ${sqlString(product.image.reviewNotes ?? (product.image.status === "ready" ? "Approved catalog image." : "Pending generation and visual QA."))}
  )`);
}

function buildSql() {
  return `-- Generated by scripts/generate-catalog-seed.mjs.
-- Do not edit manually; update src/data/catalog.ts and rerun npm run catalog:seed.
-- Contains ${catalogGroups.length} groups, ${catalogSubgroups.length} subgroups, ${catalogProducts.length} products.

begin;

insert into public.catalog_product_groups (
  id, name, description, customer_promise, measure_note, visualization_mode,
  minimum_products_required, source_urls, sort_order, is_active
) values
${groupRows().join(",\n")}
on conflict (id) do update set
  name = excluded.name,
  description = excluded.description,
  customer_promise = excluded.customer_promise,
  measure_note = excluded.measure_note,
  visualization_mode = excluded.visualization_mode,
  minimum_products_required = excluded.minimum_products_required,
  source_urls = excluded.source_urls,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active,
  updated_at = now();

insert into public.catalog_product_subgroups (
  id, group_id, name, description, customer_promise, minimum_products_required,
  sort_order, is_active
) values
${subgroupRows().join(",\n")}
on conflict (id) do update set
  group_id = excluded.group_id,
  name = excluded.name,
  description = excluded.description,
  customer_promise = excluded.customer_promise,
  minimum_products_required = excluded.minimum_products_required,
  sort_order = excluded.sort_order,
  is_active = excluded.is_active,
  updated_at = now();

insert into public.catalog_products (
  id, group_id, subgroup_id, name, short_description, material_family,
  color_name, color_hex, transparency, control_type, compatible_mounting_methods,
  sample_available, base_price_cents, price_per_square_meter_cents,
  min_width_mm, max_width_mm, min_height_mm, max_height_mm,
  commerce_bullets, measurement_warnings, is_active
) values
${productRows().join(",\n")}
on conflict (id) do update set
  group_id = excluded.group_id,
  subgroup_id = excluded.subgroup_id,
  name = excluded.name,
  short_description = excluded.short_description,
  material_family = excluded.material_family,
  color_name = excluded.color_name,
  color_hex = excluded.color_hex,
  transparency = excluded.transparency,
  control_type = excluded.control_type,
  compatible_mounting_methods = excluded.compatible_mounting_methods,
  sample_available = excluded.sample_available,
  base_price_cents = excluded.base_price_cents,
  price_per_square_meter_cents = excluded.price_per_square_meter_cents,
  min_width_mm = excluded.min_width_mm,
  max_width_mm = excluded.max_width_mm,
  min_height_mm = excluded.min_height_mm,
  max_height_mm = excluded.max_height_mm,
  commerce_bullets = excluded.commerce_bullets,
  measurement_warnings = excluded.measurement_warnings,
  is_active = excluded.is_active,
  updated_at = now();

delete from public.catalog_product_assets
where asset_type = 'product-photo'
  and product_id in (select id from public.catalog_products);

insert into public.catalog_product_assets (
  product_id, status, asset_type, url, alt, prompt, reference_source_url, review_notes
) values
${assetRows().join(",\n")};

commit;
`;
}

async function main() {
  assertCatalogCompleteness();
  await mkdir(outputDir, { recursive: true });
  await writeFile(sqlPath, buildSql());
  await writeFile(
    manifestPath,
    `${JSON.stringify(
      {
        generatedFrom: "src/data/catalog.ts",
        groups: catalogGroups.length,
        subgroups: catalogSubgroups.length,
        products: catalogProducts.length,
        completeness: catalogCompleteness,
        sqlPath: path.relative(process.cwd(), sqlPath),
      },
      null,
      2,
    )}\n`,
  );
  console.log(`Wrote ${path.relative(process.cwd(), sqlPath)}`);
  console.log(`Wrote ${path.relative(process.cwd(), manifestPath)}`);
}

await main();
